  function hasStudents(subtype, role) {
    const config = rule(subtype);
    const index = config.roles.findIndex(([name]) => name === role);
    if (index < 0 || config.unavailable.includes(index)) return false;
    return ['1.4','1.9','1.10','1.11'].includes(config.code)
      || (config.code === '3.5' && index < 2)
      || (config.code === '4.3' && index === 1)
      || (config.code === '2.9' && index >= 3);
  }
  // WORKLOAD_SCORE: Application entry point. Never accepts user-supplied weights or scores.
  function evaluate(data) {
    const config = rule(data.subtype);
    const index = config.roles.findIndex(([name]) => name === data.role);
    if (index < 0 || config.unavailable.includes(index)) return {status:'unavailable', score:null};
    const weight = config.code === '1.1' ? studentWeight(data.students) : config.roles[index][1];
    if (weight === '') return {status:'pending', score:null};
    if (weight == null) return {status:'incomplete', score:null};
    if (config.code === '3.3' && index === 3 && (studentWeight(data.students) === null || Number(data.students) <= 300)) return {status:'incomplete', score:null};
    const score = calculate({...data, basis:config.basis, weight});
    return {status:score === null ? 'incomplete' : 'calculated', score};
  }
  // Only actual inputs used by this subtype/role belong in the form or saved record.
  function fields(subtype, role) {
    const config = rule(subtype);
    const code = config.code;
    const index = config.roles.findIndex(([name]) => name === role);
    if (['1.1','1.2','1.6','1.7'].includes(code)) return ['course','role','hours','credits','students','share'];
    if (code.startsWith('1.')) return ['course','role', config.basis === 'credits' ? 'credits' : 'quantity','share'];
    if (code.startsWith('2.')) {
      const result = ['role','share'];
      if (['2.1','2.2','2.6.1','2.6.2','2.8.1','2.8.2','2.9','2.10'].includes(code) || code.startsWith('2.3.') || code.startsWith('2.4.')) result.push('source');
      if (['2.8.1','2.8.2'].includes(code)) result.push('budget');
      if (config.basis === 'quantity') result.push('quantity');
      return result;
    }
    if (['3.1','3.2','3.5'].includes(code)) return ['role'];
    if (code === '3.3') return ['role','course','quantity', ...(index === 3 ? ['students'] : [])];
    if (code === '3.4') return ['role','course','quantity','share'];
    if (code.startsWith('4.')) return ['role','organization', ...(config.basis === 'quantity' ? ['quantity'] : []), ...(code === '4.3' ? ['share'] : [])];
    return ['role'];
  }
