    return config ? {code, basis: config[0], roles: config[1], roleLabel, note: notes[code] || '', page: pages[code], unavailable: code === '2.5' ? [3] : []} : {code, basis: 'unavailable', roles: [], roleLabel, note: 'PDF มีเพียงสรุปคะแนนพิเศษ แต่ไม่มีรายละเอียดบทบาทและเกณฑ์ จึงยังคำนวณหมวดนี้ไม่ได้', unavailable: []};
