  // ===== START WORKLOAD_SCORE: สูตรคะแนนก่อนหักเพดานหมวด =====
  // งานบรรยายปริญญาตรี: ใช้จำนวนนักศึกษาจริง ไม่ใช้ช่วงจำนวนเป็นบทบาท
  function studentWeight(students) {
    if (students === '' || students == null || !Number.isSafeInteger(Number(students)) || Number(students) < 0) return null;
    return Number(students) < 100 ? 1 : Number(students) <= 250 ? 1.1 : Number(students) <= 500 ? 1.2 : 1.3;
  }
  function calculate({basis, credits, quantity, weight, share}) {
    if (!['quantity', 'credits', 'credits3', 'single', 'direct'].includes(basis)) return null;
    const units = ['single', 'direct'].includes(basis) ? 1 : basis === 'quantity' ? quantity : credits;
    if ([units, weight, share].some(value => value === '' || value == null || !Number.isFinite(Number(value)) || Number(value) < 0) || Number(share) > 100) return null;
    const score = basis === 'direct' ? Number(weight) : 200 * Number(units) / (basis === 'credits3' ? 3 : 1) * Number(weight) * Number(share) / 100;
    return Number.isFinite(score) ? score : null;
  }
